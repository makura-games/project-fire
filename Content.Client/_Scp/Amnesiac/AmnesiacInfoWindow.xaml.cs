using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Scp.Amnesiac;

[GenerateTypedNameReferences]
public sealed partial class AmnesiacInfoWindow : DefaultWindow
{
    private TimeSpan _remaining;

    public event Action? OnConfirmed;

    public AmnesiacInfoWindow()
    {
        RobustXamlLoader.Load(this);

        OkButton.OnPressed += _ =>
        {
            OnConfirmed?.Invoke();
            Close();
        };
    }

    public void SetInfo(string reagentName, string erasedMemory, TimeSpan confirmDelay)
    {
        UsedLabel.SetMessage(FormattedMessage.FromMarkupPermissive(
            Loc.GetString("amnesiac-info-used", ("name", reagentName))));
        ErasedLabel.SetMessage(FormattedMessage.FromMarkupPermissive(
            Loc.GetString("amnesiac-info-erased", ("erased", erasedMemory))));

        _remaining = confirmDelay;
        UpdateButton();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!OkButton.Disabled)
            return;

        _remaining -= TimeSpan.FromSeconds(args.DeltaSeconds);
        UpdateButton();
    }

    private void UpdateButton()
    {
        var locked = _remaining > TimeSpan.Zero;

        OkButton.Disabled = locked;
        OkButton.Text = locked
            ? Loc.GetString("amnesiac-info-ok-wait", ("seconds", (int) Math.Ceiling(_remaining.TotalSeconds)))
            : Loc.GetString("amnesiac-info-ok");
    }
}
